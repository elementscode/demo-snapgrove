export interface PhotoRef {
  imageId?: string | null;
  imageHash?: string | null;
  seedPhoto?: string | null;
}

export interface AvatarRef {
  avatarImageId?: string | null;
  avatarHash?: string | null;
  avatarSeed?: string | null;
}

export function imageUrl(id: string, hash: string): string {
  return `/images/${id}/${hash}`;
}

export function photoUrl(p: PhotoRef): string {
  if (p.imageId && p.imageHash) {
    return imageUrl(p.imageId, p.imageHash);
  }

  return SEED[p.seedPhoto ?? ""] ?? "";
}

/** An empty string means no avatar; the Avatar template draws an initial. */
export function avatarUrl(u: AvatarRef): string {
  if (u.avatarImageId && u.avatarHash) {
    return imageUrl(u.avatarImageId, u.avatarHash);
  }

  return SEED[u.avatarSeed ?? ""] ?? "";
}
